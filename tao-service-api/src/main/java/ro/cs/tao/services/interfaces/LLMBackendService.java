package ro.cs.tao.services.interfaces;

import ro.cs.tao.services.operations.OperationDescriptor;

import java.util.List;
import java.util.Map;
import java.util.function.BooleanSupplier;
import java.util.function.Consumer;

/**
 * The LLMBackendService interface defines methods for interacting with a language model backend service.
 * It provides functionalities for generating text, managing model configurations, and accessing model details.
 *
 * @author  Cosmin Cara
 * @since   2.0.0
 */
public interface LLMBackendService {

    /**
     * Returns the name of the provider for the language model backend service.
     *
     * @return The provider name as a string.
     */
    String providerName();

    /**
     * Retrieves the prefix used for configuration keys within the language model backend service.
     *
     * @return A string representing the prefix for configuration keys.
     */
    String configurationKeysPrefix();

    /**
     * Generates a response based on the given user ID and input prompt by interacting with the language model backend service.
     *
     * @param userId The identifier of the user requesting the generation. It may influence the model's behavior based on user-specific data.
     * @param prompt The text input provided as a query or instruction that guides the response generation.
     * @return A string representing the generated text from the language model in response to the given prompt.
     */
    String generate(String userId, String prompt);

    /**
     * Generates a response based on the given user ID and input prompt, interacting with the language model backend service.
     *
     * @param userId The identifier of the user requesting the generation. It may influence the model's behavior based on user-specific data.
     * @param prompt The text input provided as a query or instruction that guides the response generation.
     * @param maxTokens The maximum number of tokens to generate. This limits the length of the generated response.
     * @param temperature A value between 0 and 1 that controls the randomness of the response generation. A higher value produces more random results.
     * @return A string representing the generated text from the language model in response to the given prompt.
     */
    String generate(String userId, String prompt, int maxTokens, float temperature);

    /**
     * Generates a response using a specified set of tools, based on the given user ID and input prompt.
     * The response is generated by interacting with the language model backend service.
     *
     * @param userId The identifier of the user requesting the generation. It may influence the model's behavior based on user-specific data.
     * @param prompt The text input that serves as a query or instruction to guide the response generation.
     * @param tools A list of OperationDescriptor objects that define the operations to use during generation.
     * @param maxTokens The maximum number of tokens to generate, which limits the length of the generated response.
     * @param temperature A value between 0 and 1 that controls the randomness of the response generation. Higher values produce more random results.
     *
     * @return A string representing the generated text from the language model in response to the given prompt.
     */
    default String generateWithTools(String userId,
                                     String prompt,
                                     List<OperationDescriptor> tools,
                                     int maxTokens,
                                     float temperature) {
        return generate(userId, prompt, maxTokens, temperature);
    }

    /**
     * Generates a stream of responses based on the given user ID and input prompt, interacting with the language model backend service.
     *
     * @param userId The identifier of the user requesting the generation, which may influence the model's behavior based on user-specific data.
     * @param prompt The text input provided as a query or instruction that guides the response generation.
     * @param maxTokens The maximum number of tokens to generate, limiting the length of the generated response.
     * @param temperature A value between 0 and 1 that controls the randomness of the response generation; a higher value produces more random results.
     * @param onToken A consumer that processes each token generated by the language model, receiving the generated string token-by-token.
     */
    default void generateStream(String userId, String prompt, int maxTokens, float temperature, Consumer<String> onToken) {
        generateStream(userId, prompt, maxTokens, temperature, onToken, () -> false);
    }

    /**
     * Generates a stream of responses based on the given user ID and input prompt, interacting with the language model backend service.
     *
     * @param userId The identifier of the user requesting the generation, which may influence the model's behavior based on user-specific data.
     * @param prompt The text input provided as a query or instruction that guides the response generation.
     * @param maxTokens The maximum number of tokens to generate, limiting the length of the generated response.
     * @param temperature A value between 0 and 1 that controls the randomness of the response generation; a higher value produces more random results.
     * @param onToken A consumer that processes each token generated by the language model, receiving the generated string token-by-token.
     * @param shouldStop A condition supplier that determines whether the token generation process should stop executing.
     */
    default void generateStream(String userId, String prompt, int maxTokens, float temperature, Consumer<String> onToken, BooleanSupplier shouldStop) {
        if (shouldStop.getAsBoolean()) {
            return;
        }
        onToken.accept(generate(userId, prompt, maxTokens, temperature));
    }

    /**
     * Determines whether the language model is currently loaded in the backend service.
     *
     * @return true if the model is loaded; false otherwise.
     */
    boolean isModelLoaded();

    /**
     * Determines whether the language model is currently loaded in the backend service for a specific user.
     *
     * @param userId The identifier of the user for whom the model's loaded status is being checked.
     * @return true if the model is loaded; false otherwise.
     */
    default boolean isModelLoaded(String userId) {
        return isModelLoaded();
    }

    /**
     * Retrieves information about the currently active language model in the backend service.
     *
     * @return A string containing details about the active language model, which may include
     *         the model's name, version, and other relevant metadata.
     */
    String getModelInfo();

    /**
     * Retrieves information about the currently active language model in the backend service
     * for a specific user.
     *
     * @param userId The identifier of the user for whom the model information is requested.
     * @return A string containing details about the active language model, which may include
     *         the model's name, version, and other relevant metadata.
     */
    default String getModelInfo(String userId) {
        return getModelInfo();
    }

    /**
     * Retrieves the name of the currently active language model within the backend service.
     *
     * @return A string representing the name of the active model.
     */
    String getActiveModelName();

    /**
     * Retrieves the name of the currently active language model for a specific user within the backend service.
     *
     * @param userId The identifier of the user for whom the active model name is being requested.
     * @return A string representing the name of the active model for the specified user.
     */
    default String getActiveModelName(String userId) {
        return getActiveModelName();
    }

    /**
     * Retrieves a list of available language models from the backend service.
     *
     * @return A list of strings, each representing an available model name within the backend service.
     */
    List<String> getAvailableModels();

    /**
     * Retrieves a list of available language models that can be accessed by the specified user.
     *
     * @param userId The identifier of the user for whom the available models are being requested.
     * @return A list of strings, each representing an available model name for the specified user within the backend service.
     */
    default List<String> getAvailableModels(String userId) {
        return getAvailableModels();
    }

    /**
     * Attempts to switch the current model to a new model specified by the provided name.
     *
     * @param newModelName the name of the new model to switch to
     * @return true if the model switch was successful, false otherwise
     */
    boolean switchModel(String newModelName);

    /**
     * Switches the current model for a user to a new specified model.
     *
     * @param userId the unique identifier of the user for whom the model switch is to be performed
     * @param newModelName the name of the new model to switch to
     * @return true if the model switch was successful, false otherwise
     */
    default boolean switchModel(String userId, String newModelName) {
        return switchModel(newModelName);
    }

    /**
     * Checks whether a model download process is currently in progress.
     *
     * @return true if a model download is underway, false otherwise.
     */
    boolean isModelDownloadInProgress();

    /**
     * Checks whether a model download process is currently in progress for the specified user.
     *
     * @param userId The identifier of the user for whom to check the download status.
     * @return A boolean value indicating if the model download is in progress for the given user.
     */
    default boolean isModelDownloadInProgress(String userId) {
        return isModelDownloadInProgress();
    }

    /**
     * Retrieves the download target URL or path for a specified model.
     *
     * @return A string representing the download target location for the model.
     */
    String getModelDownloadTarget();

    /**
     * Retrieves the target location for downloading a model associated with the specified user.
     *
     * @param userId the unique identifier of the user for whom the model download target is being requested
     * @return the download target location as a string
     */
    default String getModelDownloadTarget(String userId) {
        return getModelDownloadTarget();
    }

    /**
     * Provides a message regarding the status or instructions for downloading a model.
     *
     * @return A string containing the message related to model download.
     */
    String getModelDownloadMessage();

    /**
     * Constructs and returns a default model download message for the specified user.
     *
     * @param userId The unique identifier of the user for whom the model download message is being generated.
     * @return A default message indicating the status or instructions regarding the model download for the given user.
     */
    default String getModelDownloadMessage(String userId) {
        return getModelDownloadMessage();
    }

    /**
     * Retrieves the metadata associated with the last response.
     *
     * @return a map containing key-value pairs of the last response's metadata.
     *         If no metadata is available, returns an empty map.
     */
    default Map<String, String> getLastResponseMetadata() {
        return Map.of();
    }
}
